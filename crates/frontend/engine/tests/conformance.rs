//! Q28: every recipe signs off on every proof PDK over its parameter grid, and
//! the availability table is generated from these runs, never declared. The
//! checked-in `availability.toml` must equal the generated one; set
//! `PHILIS_BLESS=1` to rewrite it after a deliberate change.
//!
//! A grid point is one call of the recipe over `n` members of one polarity at
//! one size, drawn through the spine from `plan_recipes` on: drain and gate
//! private per member, the source private or shared (the recipe joins a
//! shared one in its tile), the bulk shared (a substrate is one net).
//!
//! A point that does not sign off today is a named marker in
//! [`KNOWN_FAILURES`], with its defect and owner, and counts against its
//! recipe's availability. The failing points must equal that list by name: a
//! new failure fails, and so does a listed point that signs off, until its
//! marker goes.
//!
//! MosRatioed also draws a mirror axis: one gate net, member `k` at `2^k`
//! times the size's W (1:2 and 1:2:4 at unequal fingers), its input and no
//! other recipe's (they take members of one finger).
//!
//! A point a recipe does not apply to (a `no-recipe` refusal: Cc1d over
//! private sources) is skipped, not failed. A recipe is available on a PDK
//! when it draws at least one point there and every point it draws signs off.

use std::fmt::Write as _;

const TABLE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/availability.toml");

/// Grid points known not to sign off, by exact case name (the text before
/// a failure's `:`), each with its defect and the owner fixing it.
const KNOWN_FAILURES: [(&str, &str); 0] = [];

/// A proof PDK: its deck and, per polarity, a plain model with its sizes
/// `(W, L)` as SPICE text.
struct Proof {
    deck: &'static str,
    models: [(&'static str, &'static [(&'static str, &'static str)]); 2],
}

const PROOFS: [Proof; 2] = [
    Proof { deck: "sky130", models: [("nfet_01v8", &[("2u", "0.5u"), ("1u", "0.15u")]), ("pfet_01v8", &[("2u", "0.5u"), ("1u", "0.15u")])] },
    Proof { deck: "asap7", models: [("nmos_rvt", &[("270n", "20n"), ("54n", "20n")]), ("pmos_rvt", &[("270n", "20n"), ("54n", "20n")])] },
];

/// `n` members of `nf` fingers; `shared`: the sources on one net; `ratio`:
/// one gate net, member `k` at `2^k` times `w`.
fn netlist(n: usize, model: &str, w: &str, l: &str, nf: u16, shared: bool, ratio: bool) -> String {
    let mut ports = Vec::new();
    let mut cards = String::new();
    // `w` is SPICE text in `u` or `n`.
    let w_nm: u64 = w.strip_suffix('u').map_or_else(|| w.trim_end_matches('n').parse().unwrap(), |u| u.parse::<u64>().unwrap() * 1000);
    for k in 0..n {
        let (s, b) = (if shared { "s".to_string() } else { format!("s{k}") }, "b".to_string());
        let (g, w) = if ratio { ("g".to_string(), format!("{}n", w_nm << k)) } else { (format!("g{k}"), w.to_string()) };
        writeln!(cards, "XM{k} d{k} {g} {s} {b} {model} W={w} L={l} nf={nf}").unwrap();
        ports.push(format!("d{k}"));
        for p in [g, s, b] {
            if !ports.contains(&p) {
                ports.push(p);
            }
        }
    }
    format!(".subckt grid {}\n{cards}.ends grid\n", ports.join(" "))
}

/// Every hard finding but PEX (signoff-only, Q29), and LVS over every device.
fn findings(s: &verify::Signoff) -> Vec<String> {
    let mut out: Vec<String> = s.report.hard_violations.iter().map(|v| v.rule.clone()).filter(|r| !r.starts_with("engine/pex")).collect();
    out.extend(s.coverage.skipped_rules.iter().filter(|(r, _)| r == "lvs").map(|(r, why)| format!("{r} skipped: {why}")));
    out.extend(s.coverage.unverified.iter().map(|(k, m, n)| format!("unverified {n} {k:?} {m:?}")));
    out
}

/// The spine with one `kind` call over every device.
fn one_call(kind: engine::RecipeKind, spice: &str, pdk: &verify::Pdk) -> Result<engine::Outcome, engine::Refusal> {
    let netlist = engine::parse(spice, pdk)?;
    let cfg = engine::annotation(pdk);
    let problem = annotator::annotate(&netlist.flat, &cfg);
    let members: Vec<_> = (0..netlist.flat.devices.len()).map(|i| analog::base::DeviceId(i as u16)).collect();
    let mut calls = engine::RecipeCalls::default();
    calls.push(kind, &members, None);
    engine::run_calls(&netlist, &problem, &cfg, calls, pdk, verify::SignoffEngine::Gpurify)
}

/// Oracle: GPurify signoff on the real decks (DRC, ERC, LVS against the
/// drawn reference), independent of the recipe; [`KNOWN_FAILURES`] by name.
#[test]
fn every_recipe_conforms_on_every_proof_pdk() {
    let mut table = String::from("# Generated by tests/conformance.rs (Q28): recipe × proof PDK.\n");
    let mut failures = std::collections::BTreeMap::new();
    for kind in engine::RecipeKind::ALL {
        writeln!(table, "\n[{kind:?}]").unwrap();
        for proof in &PROOFS {
            let pdk = verify::Pdk::builtin(proof.deck).expect("a built-in deck");
            let (mut ok, mut drawn) = (true, 0);
            for (model, sizes) in proof.models {
                for &(w, l) in sizes {
                    let grid = (1..=3).flat_map(|n| [1u16, 2, 4].into_iter().flat_map(move |nf| [false, true].map(|s| (n, nf, s, false))));
                    let mirrors = (2..=3).flat_map(|n| [1u16, 2, 4].map(|nf| (n, nf, true, true)));
                    let mirrors = mirrors.filter(|_| kind == engine::RecipeKind::MosRatioed);
                    for (n, nf, shared, ratio) in grid.chain(mirrors) {
                        {
                            let spice = netlist(n, model, w, l, nf, shared, ratio);
                            let bad = match one_call(kind, &spice, &pdk) {
                                Ok(out) => findings(&out.signoff),
                                // Not this recipe's input, or a size the deck cannot draw.
                                Err(r) if r.code == "no-recipe" || r.code == "device" => continue,
                                Err(r) => vec![r.to_string()],
                            };
                            drawn += 1;
                            if !bad.is_empty() {
                                ok = false;
                                let case = format!("{kind:?} {} {model} W={w} L={l} n={n} nf={nf} shared={shared} ratio={ratio}", proof.deck);
                                failures.insert(case, format!("{bad:?}"));
                            }
                        }
                    }
                }
            }
            writeln!(table, "{} = {}", proof.deck, ok && drawn > 0).unwrap();
        }
    }
    if std::env::var_os("PHILIS_BLESS").is_some() {
        std::fs::write(TABLE, &table).expect("write availability.toml");
    }
    let checked_in = std::fs::read_to_string(TABLE).unwrap_or_default();
    let line = |(c, b): (&String, &String)| format!("{c}: {b}");
    assert_eq!(
        checked_in,
        table,
        "availability.toml differs from this run (PHILIS_BLESS=1 rewrites it):\n{}",
        failures.iter().map(line).collect::<Vec<_>>().join("\n")
    );
    let unexpected: Vec<String> = failures.iter().filter(|(c, _)| !KNOWN_FAILURES.iter().any(|(k, _)| k == c)).map(line).collect();
    let passing: Vec<&str> = KNOWN_FAILURES.iter().map(|&(k, _)| k).filter(|k| !failures.contains_key(*k)).collect();
    assert!(
        unexpected.is_empty() && passing.is_empty(),
        "grid points that do not sign off:\n{}\nknown failures that now sign off (remove their KNOWN_FAILURES marker): {passing:?}",
        unexpected.join("\n")
    );
}
